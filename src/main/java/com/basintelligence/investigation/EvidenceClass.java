package com.basintelligence.investigation;

/**
 * How much trust a piece of evidence deserves. Every tool result, evidence item and report section carries one,
 * so a reader can tell what was measured from what a model predicted and what the AI agent concluded.
 */
public enum EvidenceClass {
    /** Direct sensor readings and statistics computed from them. */
    MEASURED("Measured", "Sensor readings and statistics computed directly from them"),
    /** Deterministic rules applied to measurements (envelope limits, z-score thresholds, fault-signature rules). */
    RULE_BASED("Rule-based detection", "Deterministic rules applied to measurements; reproducible"),
    /** Output of a trained ML or vision model; carries the model's error rate and training-data limits. */
    MODEL_PREDICTION("Model prediction", "Output of a trained model; probabilistic and limited by its training data"),
    /** Maintenance manuals, machine specifications and recorded history. */
    DOCUMENTED("Documented", "Manuals, specifications and records written by people"),
    /** The agent's reasoning over the evidence above; unverified until an engineer reviews it. */
    AI_INTERPRETATION("AI interpretation", "Generated by the AI agent; not verified until an engineer reviews it");

    private final String label;
    private final String meaning;

    EvidenceClass(String label, String meaning) {
        this.label = label;
        this.meaning = meaning;
    }

    public String label() {
        return label;
    }

    public String meaning() {
        return meaning;
    }
}
