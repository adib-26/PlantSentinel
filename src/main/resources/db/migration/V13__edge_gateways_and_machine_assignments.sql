-- Per-gateway credentials for BAS / Mako Server edge nodes. Each gateway belongs to one factory and may only post
-- readings for machines in that factory. Only a SHA-256 hash of the key is stored; the key is shown once on creation.
CREATE TABLE edge_gateways (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factory_id    UUID NOT NULL REFERENCES factories (id),
    code          VARCHAR(80)  NOT NULL UNIQUE,
    description   VARCHAR(200),
    key_prefix    VARCHAR(24)  NOT NULL,
    key_hash      VARCHAR(64)  NOT NULL UNIQUE,
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_by    VARCHAR(80)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    rotated_at    TIMESTAMP WITH TIME ZONE,
    revoked_at    TIMESTAMP WITH TIME ZONE,
    last_used_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_edge_gateways_code CHECK (LENGTH(code) >= 3)
);

CREATE INDEX idx_edge_gateways_factory ON edge_gateways (factory_id);

-- Technicians see only the machines they are assigned to (plus machines of work orders assigned to them).
CREATE TABLE machine_assignments (
    device_id    UUID NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    username     VARCHAR(80) NOT NULL REFERENCES users (username) ON DELETE CASCADE,
    assigned_by  VARCHAR(80) NOT NULL,
    assigned_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (device_id, username)
);

CREATE INDEX idx_machine_assignments_user ON machine_assignments (username);
CREATE INDEX idx_maintenance_assigned_to ON maintenance_records (assigned_to);
CREATE INDEX idx_users_factory ON users (factory_id);
