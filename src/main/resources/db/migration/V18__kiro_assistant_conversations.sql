-- Conversations with Kiro on the Kiro assistant page. Each engineer's message starts one Kiro CLI run on the server
-- (role KIRO, status RUNNING until it ends). A conversation belongs to the engineer who started it and is shown to
-- nobody else. kiro_session_id is Kiro's own session id, used to continue the conversation (--resume-id).
CREATE TABLE assistant_conversations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(80) NOT NULL,
    title            VARCHAR(200) NOT NULL,
    kiro_session_id  VARCHAR(100),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_assistant_conversation_user ON assistant_conversations (username, updated_at DESC);

CREATE TABLE assistant_messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT NOT NULL REFERENCES assistant_conversations (id) ON DELETE CASCADE,
    role             VARCHAR(10) NOT NULL,
    content          TEXT,
    status           VARCHAR(20) NOT NULL,
    error_message    VARCHAR(500),
    credits          DOUBLE PRECISION,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_assistant_message_role CHECK (role IN ('USER', 'KIRO')),
    CONSTRAINT ck_assistant_message_status CHECK (status IN ('SENT', 'RUNNING', 'DONE', 'FAILED', 'TIMED_OUT', 'CANCELLED'))
);
CREATE INDEX idx_assistant_message_conversation ON assistant_messages (conversation_id, id);

-- MCP calls made by such a run carry the engineer it ran for and the Kiro message it belongs to. Both stay NULL for
-- calls with the shared agent key (Kiro started by hand).
ALTER TABLE agent_sessions ADD COLUMN on_behalf_of VARCHAR(80);
ALTER TABLE agent_tool_audit ADD COLUMN on_behalf_of VARCHAR(80);
ALTER TABLE agent_tool_audit ADD COLUMN assistant_message_id BIGINT;
ALTER TABLE agent_tool_audit ADD CONSTRAINT fk_tool_audit_assistant_message
    FOREIGN KEY (assistant_message_id) REFERENCES assistant_messages (id) ON DELETE SET NULL;
CREATE INDEX idx_tool_audit_assistant_message ON agent_tool_audit (assistant_message_id);
