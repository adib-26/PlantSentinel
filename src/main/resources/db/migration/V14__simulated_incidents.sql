-- Simulated machine incidents: an engineer plays a fault scenario on a simulated machine to rehearse the
-- detection -> risk -> investigation -> approval journey. Readings are stored with source SIMULATOR and the
-- investigation question is labelled, so simulated incidents are never mistaken for real ones.
CREATE TABLE simulated_incidents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id         UUID NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    fault             VARCHAR(40) NOT NULL,
    ramp_seconds      INTEGER NOT NULL,
    status            VARCHAR(20) NOT NULL,
    started_by        VARCHAR(80) NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reading_at   TIMESTAMP WITH TIME ZONE,
    readings          INTEGER NOT NULL DEFAULT 0,
    investigation_id  BIGINT REFERENCES investigations (id),
    ended_by          VARCHAR(80),
    ended_at          TIMESTAMP WITH TIME ZONE,
    note              VARCHAR(500),
    CONSTRAINT ck_incident_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'STOPPED')),
    CONSTRAINT ck_incident_fault CHECK (fault IN ('BEARING_WEAR', 'COOLING_DEGRADATION', 'PRESSURE_LEAK', 'OVERLOAD')),
    CONSTRAINT ck_incident_ramp CHECK (ramp_seconds BETWEEN 60 AND 7200)
);

CREATE INDEX idx_incidents_device ON simulated_incidents (device_id, started_at DESC);
CREATE INDEX idx_incidents_status ON simulated_incidents (status);
